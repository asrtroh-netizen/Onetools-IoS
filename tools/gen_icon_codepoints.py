"""Generate or check OneUI/Sources/OneUICore/Icons/MaterialIconCodepoints.swift."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import check_fixtures

ROOT = Path(__file__).resolve().parents[1]
SWIFT_OUT = ROOT / "OneUI" / "Sources" / "OneUICore" / "Icons" / "MaterialIconCodepoints.swift"
SWIFT_KEYWORDS = {
    "associatedtype",
    "break",
    "case",
    "catch",
    "class",
    "continue",
    "default",
    "defer",
    "deinit",
    "do",
    "else",
    "enum",
    "extension",
    "fallthrough",
    "false",
    "fileprivate",
    "for",
    "func",
    "guard",
    "if",
    "import",
    "in",
    "init",
    "inout",
    "internal",
    "is",
    "let",
    "nil",
    "operator",
    "private",
    "protocol",
    "public",
    "repeat",
    "rethrows",
    "return",
    "self",
    "Self",
    "static",
    "struct",
    "subscript",
    "super",
    "switch",
    "throw",
    "throws",
    "true",
    "try",
    "typealias",
    "var",
    "where",
    "while",
}


def _swift_ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def render_swift() -> tuple[str, int]:
    names = check_fixtures._icon_names()
    codepoints, families = check_fixtures._icon_codepoints()
    missing = [name for name in names if name not in codepoints]
    if missing:
        raise ValueError("missing code points for: " + ", ".join(missing))

    lines = [
        "// Generated by tools/gen_icon_codepoints.py. Do not edit by hand.",
        "",
        "public enum OneIconFamily: String, Equatable, Sendable {",
        '    case materialIcons = "MaterialIcons"',
        '    case cupertinoIcons = "CupertinoIcons"',
        "}",
        "",
        "public struct OneIconDescriptor: Equatable, Sendable {",
        "    public let name: String",
        "    public let codePoint: UInt32",
        "    public let family: OneIconFamily",
        "",
        "    public init(name: String, codePoint: UInt32, family: OneIconFamily) {",
        "        self.name = name",
        "        self.codePoint = codePoint",
        "        self.family = family",
        "    }",
        "}",
        "",
        "public enum MaterialIconCodepoints {",
    ]
    for name in names:
        cp = codepoints[name]
        ident = _swift_ident(name)
        lines.append(f"    public static let {ident}: UInt32 = 0x{cp:04X}")
    lines.append("")
    lines.append("    public static let all: [OneIconDescriptor] = [")
    for name in names:
        cp = codepoints[name]
        fam = ".cupertinoIcons" if families[name] == "CupertinoIcons" else ".materialIcons"
        lines.append(
            f'        OneIconDescriptor(name: "{name}", codePoint: 0x{cp:04X}, family: {fam}),'
        )
    lines.extend(
        [
            "    ]",
            "",
            "    public static let byName: [String: OneIconDescriptor] = Dictionary(",
            "        uniqueKeysWithValues: all.map { ($0.name, $0) }",
            "    )",
            "",
            "    public static func codePoint(for name: String) -> UInt32? {",
            '        let stripped = name.hasPrefix("Icons.") ? String(name.dropFirst(6)) : name',
            "        return byName[stripped]?.codePoint",
            "    }",
            "",
            "    public static var fixtureTree: OneTokenValue {",
            "        .list(",
            "            all.map { item in",
            "                .group([",
            '                    "name": .text(item.name),',
            '                    "codePoint": .number(Double(item.codePoint)),',
            '                    "family": .text(item.family.rawValue),',
            "                ])",
            "            }",
            "        )",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines), len(names)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify file on disk matches generated output")
    parser.add_argument("--out", type=Path, default=SWIFT_OUT, help="output Swift file path")
    args = parser.parse_args(argv)

    try:
        rendered, count = render_swift()
    except (OSError, ValueError) as exc:
        print(exc)
        return 1

    out_path: Path = args.out
    if args.check:
        if not out_path.is_file():
            print(f"missing {out_path}")
            return 1
        existing = out_path.read_text(encoding="utf-8")
        if existing != rendered:
            print(f"out of date: {out_path}")
            return 1
        print(f"ok {out_path.name} {count}")
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {out_path.name} {count}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
